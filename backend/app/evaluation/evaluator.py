"""
Independent Ground-Truth Evaluation Subsystem (Pipeline B).

CRITICAL ARCHITECTURAL ROLE:
This module operates strictly in PIPELINE B.
It has exclusive read access to `protected_ground_truth.db`.
It takes predictions generated by the Unsupervised Detection Engine (Pipeline A)
and compares them against protected labels to calculate scientific performance metrics.

It NEVER communicates ground truth back to Pipeline A.
"""

import sqlite3
import numpy as np
from typing import Dict, Any, List, Optional
from sklearn.metrics import precision_score, recall_score, f1_score, roc_auc_score, average_precision_score

from app.data_ingestion.label_isolation import get_protected_evaluation_labels
from app.core.logging import logger

class IndependentEvaluator:
    """Computes verified performance metrics against protected ground-truth labels."""

    @classmethod
    def evaluate_transaction_level(
        cls,
        conn: sqlite3.Connection,
        dataset_name: str = "SAML_D",
        risk_threshold: float = 70.0
    ) -> Dict[str, Any]:
        """
        Evaluates transaction-level predictions against protected transaction labels.
        Primarily used for SAML-D and Synthetic Simulation.
        """
        # Read protected ground truth from Pipeline B isolated store
        protected_data = get_protected_evaluation_labels(dataset_name=dataset_name)
        prot_txns = protected_data.get("transactions", {})

        if not prot_txns:
            return {
                "dataset_name": dataset_name,
                "status": "NO_PROTECTED_LABELS_AVAILABLE",
                "message": f"No protected labels recorded for {dataset_name} in evaluation store."
            }

        cursor = conn.cursor()
        cursor.execute("SELECT id, risk_score FROM transactions WHERE dataset_source = ?", (dataset_name,))
        rows = cursor.fetchall()
        predictions = {r[0]: (float(r[1]) if r[1] is not None else 0.0) for r in rows}

        y_true = []
        y_pred = []
        y_scores = []
        typology_breakdown = {}

        for txn_id, prot_item in prot_txns.items():
            true_label = prot_item.get("is_laundering")
            if true_label is None:
                # Do not count unknown labels as legitimate
                continue

            score = predictions.get(txn_id, 0.0)
            pred_binary = 1 if score >= risk_threshold else 0

            y_true.append(true_label)
            y_pred.append(pred_binary)
            y_scores.append(score / 100.0)

            # Typology tracking
            typology = prot_item.get("laundering_type", "UNKNOWN")
            if typology not in typology_breakdown:
                typology_breakdown[typology] = {"total": 0, "detected": 0}
            typology_breakdown[typology]["total"] += 1
            if pred_binary == 1:
                typology_breakdown[typology]["detected"] += 1

        if not y_true or sum(y_true) == 0:
            return {
                "dataset_name": dataset_name,
                "status": "INSUFFICIENT_LABELED_SAMPLES",
                "total_samples": len(y_true),
                "positive_samples": sum(y_true)
            }

        # Calculate metrics
        prec = precision_score(y_true, y_pred, zero_division=0)
        rec = recall_score(y_true, y_pred, zero_division=0)
        f1 = f1_score(y_true, y_pred, zero_division=0)

        # Confusion Matrix
        tp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 1)
        fp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 1)
        tn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 0)
        fn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 0)

        fpr = round(fp / max(1, (fp + tn)), 4)
        fnr = round(fn / max(1, (fn + tp)), 4)

        try:
            auc_roc = round(roc_auc_score(y_true, y_scores), 4)
            pr_auc = round(average_precision_score(y_true, y_scores), 4)
        except Exception:
            auc_roc = 0.50
            pr_auc = 0.50

        # Compute recall by typology
        typology_report = {}
        for typ, data in typology_breakdown.items():
            typology_report[typ] = {
                "total_instances": data["total"],
                "detected_count": data["detected"],
                "recall_rate": round(data["detected"] / max(1, data["total"]), 3)
            }

        return {
            "dataset_name": dataset_name,
            "evaluation_granularity": "TRANSACTION_LEVEL",
            "risk_score_threshold": risk_threshold,
            "total_evaluated_samples": len(y_true),
            "positive_laundering_count": sum(y_true),
            "negative_legitimate_count": len(y_true) - sum(y_true),
            "confusion_matrix": {
                "true_positives": tp,
                "false_positives": fp,
                "true_negatives": tn,
                "false_negatives": fn
            },
            "metrics": {
                "precision": round(float(prec), 4),
                "recall": round(float(rec), 4),
                "f1_score": round(float(f1), 4),
                "false_positive_rate": fpr,
                "false_negative_rate": fnr,
                "roc_auc": auc_roc,
                "pr_auc": pr_auc
            },
            "typology_performance": typology_report
        }

    @classmethod
    def evaluate_account_level(
        cls,
        conn: sqlite3.Connection,
        dataset_name: str = "NFPC_MULE",
        discovered_mule_account_ids: Optional[List[str]] = None
    ) -> Dict[str, Any]:
        """
        Evaluates account-level mule discovery performance against protected NFPC / Simulator account ground truth.
        """
        protected_data = get_protected_evaluation_labels(dataset_name=dataset_name)
        prot_accs = protected_data.get("accounts", {})

        if not prot_accs:
            return {
                "dataset_name": dataset_name,
                "status": "NO_PROTECTED_ACCOUNT_LABELS",
                "message": f"No account-level ground truth found for {dataset_name}."
            }

        mule_set = set(discovered_mule_account_ids or [])

        y_true = []
        y_pred = []

        for acc_id, meta in prot_accs.items():
            is_mule = meta.get("is_mule")
            if is_mule is None:
                continue

            pred = 1 if acc_id in mule_set else 0
            y_true.append(is_mule)
            y_pred.append(pred)

        if not y_true:
            return {"dataset_name": dataset_name, "status": "NO_COMPARABLE_ACCOUNTS"}

        tp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 1)
        fp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 1)
        tn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 0)
        fn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 0)

        prec = round(tp / max(1, (tp + fp)), 4)
        rec = round(tp / max(1, (tp + fn)), 4)
        f1 = round((2 * prec * rec) / max(0.001, (prec + rec)), 4)
        fpr = round(fp / max(1, (fp + tn)), 4)

        return {
            "dataset_name": dataset_name,
            "evaluation_granularity": "ACCOUNT_LEVEL_MULE_DISCOVERY",
            "total_evaluated_accounts": len(y_true),
            "true_mules_count": sum(y_true),
            "true_legitimate_accounts": len(y_true) - sum(y_true),
            "confusion_matrix": {
                "true_positives": tp,
                "false_positives": fp,
                "true_negatives": tn,
                "false_negatives": fn
            },
            "metrics": {
                "precision": prec,
                "recall": rec,
                "f1_score": f1,
                "false_positive_rate": fpr
            }
        }

    @classmethod
    def get_benchmark_comparison_matrix(cls, conn: sqlite3.Connection) -> Dict[str, Any]:
        """Returns side-by-side benchmark comparison across SAML-D, NFPC, and India Simulator."""
        saml_res = cls.evaluate_transaction_level(conn, dataset_name="SAML_D")
        india_res = cls.evaluate_transaction_level(conn, dataset_name="INDIA_SIMULATOR")
        nfpc_res = cls.evaluate_account_level(conn, dataset_name="NFPC_MULE")

        return {
            "datasets": {
                "SAML_D": saml_res,
                "NFPC_MULE": nfpc_res,
                "INDIA_SIMULATOR": india_res
            },
            "evaluation_status": "PROTECTED_GROUND_TRUTH_EVALUATION_ACTIVE"
        }
